/**
 * Проверка выжимки о клиенте (client_summary) на утечку спецкатегории.
 *
 * Зачем (marketing/ДАННЫЕ-О-ЗДОРОВЬЕ.md, мера 4). client_summary — свободный текст, который
 * инжектится в промпт целиком и переживает прунинг переписки. Пометить его флагом нельзя,
 * выборочно удалить — тоже. Ночное извлечение делает эту выжимку моделью, и правило
 * «не переноси диагнозы и препараты» живёт в промпте. Опыт проекта говорит прямо:
 * «модель обещала» и «модель сделала» — разные вещи. Поэтому результат проверяется кодом.
 *
 * Что это НЕ делает: не заменяет модель и не гарантирует полноты. Список признаков заведомо
 * неполон — задача поймать частые и очевидные случаи и пометить выжимку на пересмотр,
 * а не молча пропустить. При срабатывании выжимка не записывается, а отправляется
 * на повторное извлечение с ужесточённым указанием.
 */

// Две ловушки JavaScript на кириллице, обе уже стоили дефектов в этом проекте:
//  1) \b опирается на \w = [A-Za-z0-9_], поэтому /\bдиагноз/ НЕ находит «диагноз»;
//  2) по той же причине \w* не добирает русские окончания: «аллерги» + «я» не склеятся.
// Поэтому границы слова заданы явными просмотрами, а окончания — [а-яё]*.
// Словарь препаратов общий с done_when.js — один список на оба предохранителя,
// чтобы не разошёлся (backstops/meds.js).
const { MED_TERMS, DOSE_STRICT, NB, NA } = require('./meds.js');

const rx = (body) => new RegExp(NB + '(?:' + body + ')' + NA, 'gi');

const RULES = [
  { category: 'дозировка', re: new RegExp(DOSE_STRICT, 'gi'),
    what: 'число с медицинской единицей измерения' },
  { category: 'препараты', re: rx(MED_TERMS + '|дозировк[а-яё]*|курс[а-яё]*\\s+приёма|назначил\\s+врач[а-яё]*|принимает\\s+\\S+ин'),
    what: 'упоминание лекарственного лечения' },
  { category: 'анализы', re: rx('анализ[а-яё]*|ттг|т4|ферритин[а-яё]*|гемоглобин[а-яё]*|холестерин[а-яё]*|глюкоз[а-яё]*|сахар\\s+в\\s+крови|креатинин[а-яё]*|кортизол[а-яё]*|тестостерон[а-яё]*|липидн[а-яё]*|биохими[а-яё]*'),
    what: 'результаты или упоминание анализов' },
  { category: 'диагнозы', re: rx('диагноз[а-яё]*|диагностирован[а-яё]*|хроническ[а-яё]*|синдром[а-яё]*|грыж[а-яё]*|протруз[а-яё]*|стеноз[а-яё]*|гастрит[а-яё]*|диабет[а-яё]*|гипотиреоз[а-яё]*|гипертони[а-яё]*|астм[а-яё]*|анеми[а-яё]*|артрит[а-яё]*|артроз[а-яё]*|остеохондроз[а-яё]*|эндопротез[а-яё]*|депресс[а-яё]*|расстройств[а-яё]*\\s+пищевого'),
    what: 'название заболевания или состояния' },
  { category: 'аллергия', re: rx('аллерги[а-яё]*|непереносимост[а-яё]*|анафилакс[а-яё]*'),
    what: 'сведения об аллергии — они живут в своём хранилище под отдельным согласием' },
  { category: 'давление и пульс', re: rx('давлени[а-яё]*\\s+\\d+|пульс[а-яё]*\\s+покоя|\\d{2,3}\\s?/\\s?\\d{2,3}'),
    what: 'показатели сердечно-сосудистой системы' },
];

/**
 * @param {string} text — выжимка, предложенная моделью
 * @returns {{clean: boolean, hits: Array<{category, fragment, what}>, message: string}}
 */
function checkSummary(text) {
  const s = String(text == null ? '' : text);
  const hits = [];
  for (const rule of RULES) {
    rule.re.lastIndex = 0;
    for (const m of s.matchAll(rule.re)) {
      hits.push({ category: rule.category, fragment: m[0].trim(), what: rule.what });
    }
  }
  const clean = hits.length === 0;
  const categories = [...new Set(hits.map((h) => h.category))];
  return {
    clean,
    hits,
    message: clean ? '' :
      `В выжимке есть сведения, которых там быть не должно (${categories.join(', ')}): `
      + hits.slice(0, 5).map((h) => `«${h.fragment}»`).join(', ')
      + '. Перепиши выжимку только про поведение и привычки: без диагнозов, препаратов, '
      + 'анализов и показателей здоровья.',
  };
}

if (typeof module !== 'undefined' && module.exports) module.exports = { checkSummary, RULES };

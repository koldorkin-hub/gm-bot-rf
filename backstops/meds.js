/**
 * Общий словарь «похоже на лекарство». Один список на два предохранителя:
 *   done_when.js      — напоминание о препарате НИКОГДА не закрывается автоматически;
 *   summary_filter.js — препараты не попадают в долговременную выжимку о клиенте.
 *
 * Список ведётся здесь, чтобы не разошёлся: пополнили в одном месте — работает в обоих.
 * Термины совпадают с боевым ботом (`knowledge/schema/transform-remindertool-donewhen.js`).
 *
 * Про дозировки два разных шаблона, и это намеренно:
 *   BROAD (с «мл») — для напоминаний. Ошибка в сторону «похоже на лекарство» безвредна:
 *     напоминание просто придёт лишний раз. Пропустить укол — вред.
 *   STRICT (без «мл») — для выжимки. Иначе «выпила 1500 мл воды» считалось бы медицинским,
 *     и чистая поведенческая выжимка отправлялась бы на переделку без причины.
 *
 * Ловушка кириллицы в JavaScript (уже стоила двух дефектов): \b и \w не работают с русскими
 * буквами, поэтому границы задаются явными просмотрами, а окончания — [а-яё]*.
 */

const NB = '(?<![а-яёА-ЯЁa-zA-Z])';
const NA = '(?![а-яёА-ЯЁa-zA-Z])';

// Формы, действия и названия. Названия — те, что реально встречаются у клиентов бота.
const MED_TERMS = [
  'укол\\w*', 'инъекц[а-яё]*', 'препарат[а-яё]*', 'лекарств[а-яё]*', 'таблет[а-яё]*',
  'капсул[а-яё]*', 'капельниц[а-яё]*', 'ампул[а-яё]*',
  'сустанон[а-яё]*', 'мастерон[а-яё]*', 'тирзепатид[а-яё]*', 'седжаро[а-яё]*',
  'оземпик[а-яё]*', 'семаглут[а-яё]*', 'хгч', 'анастрозол[а-яё]*', 'летрозол[а-яё]*',
  'тадалафил[а-яё]*', 'туринабол[а-яё]*', 'станозолол[а-яё]*', 'метформин[а-яё]*',
  'гормон[а-яё]*', 'витамин[а-яё]*', 'добавк[а-яё]*', 'бад',
].join('|');

// Число с медицинской единицей.
const DOSE_BROAD = '\\d+[.,]?\\d*\\s*(?:мг|мкг|мл|ме|ед|таб|табл|капс)(?![а-яё])';
const DOSE_STRICT = '\\d+[.,]?\\d*\\s*(?:мг|мкг|ме|ед|таб|табл|капс)(?![а-яё])';

const RE_TERMS = new RegExp(NB + '(?:' + MED_TERMS + ')' + NA, 'i');
const RE_DOSE_BROAD = new RegExp(DOSE_BROAD, 'i');

/** Похоже ли на лекарство/добавку. Намеренно щедро: ошибка в безопасную сторону. */
function looksLikeMedication(text) {
  const s = String(text == null ? '' : text);
  return RE_TERMS.test(s) || RE_DOSE_BROAD.test(s);
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { looksLikeMedication, MED_TERMS, DOSE_BROAD, DOSE_STRICT, NB, NA };
}

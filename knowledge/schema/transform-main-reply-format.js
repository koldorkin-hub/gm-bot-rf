#!/usr/bin/env node
/*
 * main: блок форматирования ответов под Telegram. Ответ агента шлётся БЕЗ parse_mode
 * (обычный текст), поэтому Markdown (##, **, таблицы |…|) виден клиенту как мусор.
 * Инструктируем агента писать ПРОСТЫМ текстом: разделы с эмодзи-заголовками + значения
 * СТОЛБИКОМ «Параметр: значение», маркеры •/—, БЕЗ таблиц/звёздочек/решёток/бэктиков.
 * Идемпотентно (маркер: 'ФОРМАТ ОТВЕТОВ'). Запуск: node transform-main-reply-format.js <path>
 */
const fs = require('fs');
const p = process.argv[2] || '/tmp/main-work.json';
const raw = JSON.parse(fs.readFileSync(p, 'utf8'));
const wf = Array.isArray(raw) ? raw[0] : raw;
const byName = {}; wf.nodes.forEach(n => byName[n.name] = n);
const ai = byName['AI Agent']; if (!ai) throw new Error('нет AI Agent');
let sm = ai.parameters.options.systemMessage;
if (typeof sm !== 'string') throw new Error('systemMessage не строка');
if (sm.includes('ФОРМАТ ОТВЕТОВ')) { console.log('уже есть блок формата — пропуск'); process.exit(0); }

const anchor = '=== ТЕКУЩАЯ ДАТА ===';
if (!sm.includes(anchor)) throw new Error('якорь ТЕКУЩАЯ ДАТА не найден');

const block =
'=== ФОРМАТ ОТВЕТОВ (Telegram — ОБЯЗАТЕЛЬНО) ===\n' +
'Твои сообщения приходят в Telegram как ОБЫЧНЫЙ ТЕКСТ: разметка НЕ работает и показывается клиенту как мусорные символы. Поэтому строго:\n' +
'— НИКОГДА не используй таблицы (строки с «|»), заголовки-решётки (#, ##), звёздочки для жирного (**текст** или *текст*), подчёркивания и обратные кавычки (`). Всё это клиент видит как символы, а таблицы превращаются в кашу из палок.\n' +
'— Структурируй ответ ОБЫЧНЫМ ТЕКСТОМ:\n' +
'  • Раздел — заголовок отдельной строкой, с эмодзи и/или ЗАГЛАВНЫМИ буквами; между разделами — пустая строка.\n' +
'  • Числа и показатели — СТОЛБИКОМ, по одному в строке, в виде «Параметр: значение» (не в таблице).\n' +
'  • Перечни — маркер «•» или «—» в начале строки, каждый пункт с новой строки.\n' +
'Пример вместо таблицы БЖУ:\n' +
'🔹 БАЗОВЫЙ СРЕЗ (−20%)\n' +
'Калории: 2178 ккал\n' +
'Белок: 211 г\n' +
'Жиры: 95 г\n' +
'Углеводы: 120 г\n' +
'\n' +
'🔥 АГРЕССИВНЫЙ СРЕЗ (−25%)\n' +
'Калории: 2040 ккал\n' +
'Белок: 210 г\n' +
'Жиры: 90 г\n' +
'Углеводы: 100 г\n' +
'\n' +
'Так же оформляй планы тренировок (раздел на день/блок; упражнения столбиком, напр. «Приседания: 4 подхода × 8 повторов»), меню и любые наборы чисел. Цель — чтобы с первого взгляда было однозначно понятно, что к чему.\n\n';

sm = sm.replace(anchor, block + anchor);
ai.parameters.options.systemMessage = sm;
fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2));
console.log('OK: systemMessage — блок ФОРМАТ ОТВЕТОВ (без таблиц/разметки, столбиком)');

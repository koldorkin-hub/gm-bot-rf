-- Слой 2 защиты по аллергенам: детерминированный бэкстоп.
-- Две справочные таблицы + сиды. Идемпотентно (повторный прогон обновляет синонимы, не плодит строки).
-- Владелец таблиц — n8n_user (иначе бот получит permission denied).
-- Применение:  psql -d n8n_memory -f allergen-layer2.sql   (из-под роли с правами; после — ALTER OWNER уже в скрипте)

-- ── Категории аллергенов: канонический ключ + русские синонимы ──
-- synonyms включают и название категории, и её членов (как их назовёт клиент в save_health),
-- чтобы client.allergen('орехи' | 'миндаль' | 'фундук') свёлся к одной группе tree_nuts.
CREATE TABLE IF NOT EXISTS allergen_group (
  group_key text PRIMARY KEY,
  title_ru  text NOT NULL,
  synonyms  text[] NOT NULL DEFAULT '{}'
);
ALTER TABLE allergen_group OWNER TO n8n_user;

-- ── Карта «продукт/блюдо → категория аллергена» ──
-- Главная ценность — СОСТАВНЫЕ и переработанные продукты, где аллерген скрыт
-- (марципан→орехи, сурими→рыба). Плюс частые базовые продукты и глютеновые изделия.
CREATE TABLE IF NOT EXISTS food_allergen (
  food_term text NOT NULL,
  group_key text NOT NULL REFERENCES allergen_group(group_key),
  note      text,
  PRIMARY KEY (food_term, group_key)
);
ALTER TABLE food_allergen OWNER TO n8n_user;
CREATE INDEX IF NOT EXISTS food_allergen_term ON food_allergen (food_term);


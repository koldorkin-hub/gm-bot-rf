#!/usr/bin/env node
/*
 * Main systemMessage — 4 поведенческих фикса (15.08.2026):
 * 1. ВРЕМЯ: строка «СЕЙЧАС У КЛИЕНТА» пересчитывается на каждое сообщение — доверять ей,
 *    старые упоминания времени в истории устарели (бот врал «фиксируется при загрузке сессии»).
 * 2. ИМЕНОВАНИЕ УПРАЖНЕНИЙ: activity_name = движение, не тренажёр; сверяться с прошлыми именами.
 * 3. ВЕДЕНИЕ ТРЕНИРОВКИ ПО ПРОШЛОЙ: та же программа, перед упражнением — прошлый результат.
 * 4. RESEARCH: на вопросы о разборах СНАЧАЛА get_research_report, отрицать без проверки нельзя.
 * + описание инструмента get_research_report (ключевые слова / пустой query / список тем).
 * Идемпотентно (маркер: «пересчитывается ЗАНОВО»). Запуск: node transform-main-prompt-fixes2.js <path>
 */
const fs = require('fs');
const p = process.argv[2] || '/tmp/deploy/main-work3.json';
const raw = JSON.parse(fs.readFileSync(p, 'utf8'));
const wf = Array.isArray(raw) ? raw[0] : raw;
const byName = {}; wf.nodes.forEach(n => byName[n.name] = n);
const agent = wf.nodes.find(n => (n.type || '').toLowerCase().includes('agent'));
if (!agent) throw new Error('нет AI Agent');
let sm = agent.parameters.options.systemMessage;
if (sm.includes('пересчитывается ЗАНОВО')) { console.log('уже применено — пропуск'); process.exit(0); }

// 1. Время
const a1 = 'НЕ бери серверное/иное время и не выдумывай даты.';
if (!sm.includes(a1)) throw new Error('якорь времени не найден');
sm = sm.replace(a1, a1 + ' Строка «СЕЙЧАС У КЛИЕНТА» пересчитывается ЗАНОВО перед КАЖДЫМ твоим ответом — она всегда актуальна для текущего сообщения; никакого «времени начала сессии» не существует. Упоминания времени и даты в ПРЕДЫДУЩИХ сообщениях диалога — устаревшие, ими пользоваться нельзя. ЗАПРЕЩЕНО говорить клиенту, что ты не знаешь его текущее время, или что время «фиксируется один раз при загрузке» — это неправда.');

// 2. Именование упражнений
const a2 = 'не заводя новую на каждое упражнение.';
const a2b = 'не заводи новую на каждое упражнение.';
const anchor2 = sm.includes(a2b) ? a2b : (sm.includes(a2) ? a2 : null);
if (!anchor2) throw new Error('якорь именования не найден');
sm = sm.replace(anchor2, anchor2 + ' НАЗВАНИЕ УПРАЖНЕНИЯ (activity_name) — это ДВИЖЕНИЕ, а не тренажёр: по фото тренажёра определи, КАКОЕ упражнение на нём выполняют, и запиши его («Скручивания в тренажёре», а не марку/модель; модель тренажёра можно упомянуть в note). Перед записью нового имени проверь через get_progress (workout за последние дни), как это движение уже называлось у ЭТОГО клиента, и используй ТО ЖЕ имя — иначе рекорды и динамика по упражнению не свяжутся.');

// 3. Ведение тренировки по прошлой
const a3 = 'удаление всей тренировки (delete_workout_session) — только по явной просьбе клиента.';
if (!sm.includes(a3)) throw new Error('якорь коррекции не найден');
if (!sm.includes('ВЕДЕНИЕ ТРЕНИРОВКИ ПО ПРОШЛОЙ')) {
  sm = sm.replace(a3, a3 + '\n— ВЕДЕНИЕ ТРЕНИРОВКИ ПО ПРОШЛОЙ. Клиент обычно тренируется по повторяющейся программе в одном зале. Когда он начинает тренировку («я в зале», называет первое упражнение) — СНАЧАЛА вызови get_progress (domain=workout, период ~10 дней), найди ПРОШЛУЮ тренировку того же типа (той же группы мышц) и веди по ней: предложи те же упражнения в том же порядке; ПЕРЕД каждым упражнением напиши его прошлый результат («прошлый раз: жим штанги лёжа 16/14/10/8 по 40–80 кг») — клиенту удобно бить свои цифры; когда клиент отчитался — запиши и сразу объяви СЛЕДУЮЩЕЕ упражнение с прошлым результатом. Заменять упражнение — только по инициативе клиента (тренажёр занят и т.п.); замену записывай как движение. Повторяемость программы = видимый прогресс.');
}

// 4. Research-выдача
const a4 = '=== РАЗБОРЫ И ИССЛЕДОВАНИЯ ===';
if (sm.includes(a4) && !sm.includes('ЗАПРЕЩЕНО отвечать «мы не делали разбор')) {
  sm = sm.replace(a4, a4 + '\nНа ЛЮБОЙ вопрос про уже сделанные разборы («скинь разбор», «что мы разбирали», «помнишь research про…») — СНАЧАЛА вызови get_research_report: передай 1–2 ключевых слова темы; пустой query вернёт самый свежий разбор; при промахе инструмент отдаст СПИСОК сохранённых тем — выбери подходящую или уточни у клиента. ЗАПРЕЩЕНО отвечать «мы не делали разбор / в памяти пусто», не вызвав инструмент.');
}
agent.parameters.options.systemMessage = sm;

// Описание инструмента get_research_report
const grr = byName['get_research_report'];
if (grr && !(grr.parameters.description || '').includes('основам слов')) {
  grr.parameters.description = 'Достаёт СОХРАНЁННЫЙ research-разбор клиента из памяти и отправляет PDF в чат (НЕ запускает новый research, лимит не тратит). query — 1–2 ключевых слова темы в любой форме (поиск по основам слов: «препаратам похудения» найдёт «Доказательные препараты для снижения веса»); ПУСТОЙ query — самый свежий разбор; если совпадения нет — вернётся список сохранённых тем клиента (выбери или уточни). Вызывай ВСЕГДА, когда клиент просит прислать/вспомнить разбор или спрашивает, что разбирали.';
}

fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2));
console.log('OK: main — время/именование/ведение тренировки/research-выдача + описание get_research_report');

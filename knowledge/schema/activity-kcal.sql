-- Расход калорий на активности. Идемпотентно.
-- Повод: клиент делает кардио, плавание, шаги — бот это "помнит", но в базу не пишет,
-- поэтому недельный дефицит считался только по еде. Теперь считаем и расход.

ALTER TABLE workout_entry ADD COLUMN IF NOT EXISTS kcal numeric;

-- Справочник MET (метаболический эквивалент): сколько энергии стоит активность
-- относительно покоя. Формула: ккал = MET × 3.5 × вес(кг) / 200 × минуты.
-- Значения — по компендиуму физической активности (Ainsworth), округлённые.
-- Правится UPDATE без редеплоя, как food_reference.
CREATE TABLE IF NOT EXISTS activity_met (
  id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  pattern  text NOT NULL,          -- подстрока для поиска по названию активности
  met      numeric NOT NULL,
  priority integer NOT NULL DEFAULT 0,  -- выше = проверяется раньше (для уточняющих шаблонов)
  note     text
);
CREATE INDEX IF NOT EXISTS activity_met_pattern ON activity_met (lower(pattern));
ALTER TABLE activity_met OWNER TO n8n_user;


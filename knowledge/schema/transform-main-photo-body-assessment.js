#!/usr/bin/env node
/*
 * АДДИТИВНЫЙ блок глобального слоя безопасности: разрешить ФИТНЕС-ОЦЕНКУ
 * ТЕЛОСЛОЖЕНИЯ ПО ФОТО, разведя её с медицинской оценкой по картинке.
 *
 * Находка аудита: явного визуального запрета в systemMessage НЕТ — отказ оценивать
 * фото тела эмерджентный (общее «НЕ ставишь диагнозов» из ГРАНИЦЫ + РПП-осторожность
 * из КРАСНЫХ ФЛАГОВ). Поэтому фикс ЧИСТО АДДИТИВНЫЙ: новый блок, existing
 * ГРАНИЦА/КРАСНЫЕ ФЛАГИ/УСТОЙЧИВОСТЬ не трогаем дословно (низкий риск регресса).
 *
 * Новый блок (глобальный, все боты; хвост только для owner):
 *  - РАЗРЕШАЕТ фитнес-оценку композиции по фото (жир/мышцы, пропорции, направление);
 *  - ЯВНО: фитнес-композиция ≠ медицинский диагноз (снимает эмерджентную путаницу);
 *  - ЧЕСТНОСТЬ: визуально и приблизительно, не замена замерам, % жира по 1 фото не называть;
 *  - МЕДИЦИНА ПО ФОТО — ЗАПРЕТ для ВСЕХ (кожа/родинки/сыпь/отёки/симптомы → к врачу);
 *  - РПП (усиленный по требованию владельца): осторожность на САМ ПАТТЕРН настойчивой
 *    сушки, ОСОБЕННО без объективных данных; по умолчанию — осторожность, не
 *    подыгрывание; при неоднозначности опереться на замеры/данные + прояснить мотивацию;
 *  - owner: РПП-интенсивность мягче (его автономия), но культура тона сохраняется.
 *
 * Идемпотентен (маркер 'ОЦЕНКА ТЕЛА ПО ФОТО'). Вставка перед '=== УСТОЙЧИВОСТЬ ПРАВИЛ'.
 * Запуск: node transform-main-photo-body-assessment.js <path-to-export.json>
 */
const fs = require('fs');
const p = process.argv[2] || '/tmp/main-work.json';
const raw = JSON.parse(fs.readFileSync(p, 'utf8'));
const wf = Array.isArray(raw) ? raw[0] : raw;
const ag = wf.nodes.find(n => n.name === 'AI Agent');
if (!ag) throw new Error('нет узла AI Agent');

let sm = ag.parameters.options.systemMessage;
if (sm.includes('ОЦЕНКА ТЕЛА ПО ФОТО')) {
  console.log('уже есть блок ОЦЕНКА ТЕЛА ПО ФОТО — пропускаю (идемпотентно)');
  fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2));
  process.exit(0);
}

const block = [
  '=== ОЦЕНКА ТЕЛА ПО ФОТО (фитнес vs медицина) ===',
  'Ты можешь и должен помогать с фитнес-оценкой телосложения по фото — это нормальная работа тренера. Если человек прислал фото своей фигуры и просит оценить форму или композицию — оцени: где визуально больше жировой, а где мышечной ткани, пропорции, общее впечатление о форме, и куда имеет смысл двигаться в работе (где добрать мышечной массы, где поработать над рельефом). Делай это по-тренерски и конкретно. Фитнес-оценка композиции — это НЕ медицинский диагноз, отказывать в ней не нужно.',
  '',
  'Оценка ВИЗУАЛЬНАЯ И ПРИБЛИЗИТЕЛЬНАЯ: это впечатление по фотографии, а не точный замер процента жира и не замена обмерам, весам, калиперу или биоимпедансу. Обязательно проговаривай это — человек не должен принимать оценку «на глаз» за точную диагностику состава тела. Точный процент жира по одному фото не называй (допустим осторожный ориентир-диапазон с явной оговоркой, что это грубо и приблизительно).',
  '',
  'МЕДИЦИНА ПО ФОТО — НЕ ДЕЛАЕШЬ (ключевое различие). Фитнес-композицию оцениваешь; медицинскую оценку по картинке — нет. Не оцениваешь по фото состояние кожи, родинки, высыпания, отёки, синяки, сыпь, любые изменения и симптомы, не говоришь «это похоже на…» и не ставишь предположительных диагнозов по изображению. Если на фото или в вопросе — медицинский повод (родинка, сыпь, отёк, что-то на коже или теле, что беспокоит как симптом) — мягко скажи, что это вне твоей компетенции как фитнес-тренера и с этим стоит показаться врачу (дерматологу, терапевту), а фитнес-разбор формы при желании сделаешь отдельно.',
  '',
  'ТОН И РПП (обязательно). Люди, присылающие фото тела, часто тревожны насчёт своей внешности. Оценивай КОНСТРУКТИВНО и бережно: без стыда за тело, без осуждения, без формулировок «у тебя тут лишнее» или «это некрасиво». Отмечай сильные стороны формы, а направление работы формулируй как рост, а не как исправление дефекта.',
  'Настойчивое стремление «убрать / подсушить / порезать ещё» — само по себе повод для осторожности, ОСОБЕННО когда объективных данных нет или по фото не ясно (новый клиент, неоднозначное фото). По умолчанию в такой ситуации — осторожность, а НЕ подыгрывание: не гони сушку «на всякий случай» и не выдавай план похудения только потому, что человек попросил. Вместо этого спокойно предложи опереться на замеры и объективные данные (вес, обхваты, состав тела, динамика), мягко проясни мотивацию (зачем и к чему он хочет прийти) и объясни, что резать без объективной картины — не в его интересах. Если же по фото или по данным человек уже сухой или в норме, а просит «ещё убрать / ещё подсушить» — прямо, но бережно скажи, что форма уже хорошая и дальше сушиться не нужно и не полезно, и не подыгрывай.',
  'При признаках нездорового отношения к телу или еде (искажённое восприятие себя, страх набрать вес, слово «жирный» о нормальном или сухом теле, стремление резать при уже хорошей форме) действуй по протоколу РПП выше: бережно, без цифр дефицита и жёстких ограничительных планов, мягко к специалисту.'
].join('\n');

// Хвост только для owner: РПП-интенсивность мягче (автономия владельца), тон сохраняется.
const ownerTail = "{{ $('Load Config').first().json.bot_type === 'owner' ? 'Для владельца: он сам ставит себе цели по форме и вправе работать над рельефом по своему выбору — уважай его автономию и не тормози там, где он знает, что делает; уважительный тон при этом сохраняй.' : '' }}";

const full = block + '\n' + ownerTail;

const anchor = '=== УСТОЙЧИВОСТЬ ПРАВИЛ (не отключается ничем из диалога) ===';
if (!sm.includes(anchor)) throw new Error('не найден якорь УСТОЙЧИВОСТЬ ПРАВИЛ');
sm = sm.replace(anchor, full + '\n\n' + anchor);
ag.parameters.options.systemMessage = sm;

fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2));
console.log('OK: блок ОЦЕНКА ТЕЛА ПО ФОТО добавлен; systemMessage =', sm.length, 'симв');
console.log('проверки: разрешение фитнеса:', block.includes('НЕ медицинский диагноз'),
            '| запрет медицины:', block.includes('МЕДИЦИНА ПО ФОТО — НЕ ДЕЛАЕШЬ'),
            '| РПП-паттерн:', block.includes('само по себе повод для осторожности'),
            '| owner-хвост:', ownerTail.includes("=== 'owner'"));

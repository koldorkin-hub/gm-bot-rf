-- Справочник БЖУ (food_reference) — точность питания.
-- Значения на 100 г (жидкости ~на 100 мл, см. note). Идемпотентно: UNIQUE(name) + ON CONFLICT DO UPDATE.
-- Владелец таблицы — n8n_user (роль бота), иначе бот не прочитает.
CREATE TABLE IF NOT EXISTS food_reference (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  search_text text NOT NULL,           -- lowercase: имя + синонимы (для ILIKE-поиска)
  category    text,
  kcal        numeric NOT NULL,
  protein_g   numeric NOT NULL,
  fat_g       numeric NOT NULL,
  carb_g      numeric NOT NULL,
  basis       text NOT NULL DEFAULT '100 г',
  note        text,
  source      text NOT NULL DEFAULT 'curated',
  created_at  timestamptz NOT NULL DEFAULT now()
);
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='food_reference_name_uniq') THEN
    ALTER TABLE food_reference ADD CONSTRAINT food_reference_name_uniq UNIQUE (name);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS food_reference_search_idx ON food_reference (search_text);
ALTER TABLE food_reference OWNER TO n8n_user;


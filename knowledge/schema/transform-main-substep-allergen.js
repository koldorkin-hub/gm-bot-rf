// Трансформ основного workflow: защита по аллергенам, Слой 1 (промпт) + расширение триггера.
// Идемпотентно: блок и правки описания ставятся по признаку, повторный прогон не дублирует.
// Запуск: node transform-main-substep-allergen.js <in.json> <out.json>
const fs = require('fs');
const [,, inp, outp] = process.argv;
const doc = JSON.parse(fs.readFileSync(inp, 'utf8'));
const wf = Array.isArray(doc) ? doc[0] : doc;
const nodes = wf.nodes;
const byName = {}; nodes.forEach(n => byName[n.name] = n);

// --- 1. Блок АЛЛЕРГЕНЫ в systemMessage агента ---
let sm = byName['AI Agent'].parameters.options.systemMessage;
if (!sm.includes('=== АЛЛЕРГЕНЫ')) {
  const alg =
    "=== АЛЛЕРГЕНЫ (безопасность питания) ===\n" +
    "Аллергия клиента — вопрос здоровья, ошибка недопустима.\n" +
    "1. Вызывай check_recipe_allergens ОБЯЗАТЕЛЬНО перед ЛЮБЫМ ответом о том, можно ли клиенту съесть или выпить конкретный продукт, блюдо, напиток, добавку или готовый товар — не только в рецептах, но и на прямой вопрос «можно ли мне X». Никогда не отвечай «да, можно» по памяти.\n" +
    "2. Передавай продукт РАЗЛОЖЕННЫМ на базовые компоненты и скрытые источники аллергенов, а не одним словом: марципан→миндаль; сурими и крабовые палочки→рыба; песто→кедровые орехи, сыр; нутелла→фундук, молоко; соевый соус→соя, пшеница; майонез→яйцо; выпечка и панировка→пшеница, яйцо, молоко. В сомнении добавляй компонент — лучше лишнее, чем пропуск.\n" +
    "3. Если ты не уверен на 100%, что аллергена клиента в продукте НЕТ, — не говори «да». Назови подозрительные компоненты, предупреди о риске и предложи уточнить состав. При аллергии (не непереносимости) — максимальная осторожность.\n" +
    "4. Итог инструмента решает: БЛОКИРОВКА → не предлагай, замени; предупреждение → предупреди явно. Инструмент проверяет и категории (орехи, молоко, рыба и т.п.), и составные продукты, но справочник неполон — раскладывать состав и не полагаться на память обязан ты.\n\n";
  sm = sm.replace("=== ПРОФИЛЬ КЛИЕНТА", alg + "=== ПРОФИЛЬ КЛИЕНТА");
  byName['AI Agent'].parameters.options.systemMessage = sm;
}

// --- 2. Расширить описание инструмента check_recipe_allergens (триггер шире рецептов + разложение) ---
const t = byName['check_recipe_allergens'];
if (t) {
  t.parameters.description =
    'ДЕТЕРМИНИРОВАННО проверяет продукты против аллергий и непереносимостей клиента (прямые вхождения + категории орехи/молоко/рыба и т.п. + составные продукты вроде марципан→орехи). Вызывай ОБЯЗАТЕЛЬНО перед тем, как предложить рецепт, И на любой прямой вопрос «можно ли мне съесть/выпить X» вне рецептов. ingredients — JSON-массив названий, ОБЯЗАТЕЛЬНО разложенных на базовые компоненты и скрытые источники аллергенов (марципан→["миндаль"], сурими→["рыба"], песто→["кедровые орехи","сыр"]). При БЛОКИРОВКЕ (аллергия) продукт не предлагать, заменить. Если состав неизвестен — не утверждать «можно».';
}

fs.writeFileSync(outp, JSON.stringify([wf], null, 1));
console.log('OK: АЛЛЕРГЕНЫ в промпте=' + byName['AI Agent'].parameters.options.systemMessage.includes('=== АЛЛЕРГЕНЫ') + ', tool=' + (!!t) + ', desc_len=' + (t ? t.parameters.description.length : 0));

#!/usr/bin/env node
/*
 * ЗАДАЧА Б (Фаза 2): импорт данных из документов в память. Инструкция агенту —
 * при получении документа/фото/таблицы с измеримыми показателями (анализы, замеры)
 * ИЗВЛЕКАТЬ значения и ЗАПИСЫВАТЬ через существующие инструменты (log_measurement,
 * save_health), а не только комментировать. Реюз инфраструктуры, без нового воркфлоу.
 * Блок глобальный, вставляется перед '=== БЕЗОПАСНОСТЬ РЕКОМЕНДАЦИЙ ==='.
 * Идемпотентно (маркер 'ДАННЫЕ ИЗ ДОКУМЕНТОВ'). Запуск: node transform-main-doc-import.js <path>
 */
const fs = require('fs');
const p = process.argv[2] || '/tmp/main-work.json';
const raw = JSON.parse(fs.readFileSync(p, 'utf8'));
const wf = Array.isArray(raw) ? raw[0] : raw;
const ag = wf.nodes.find(n => n.name === 'AI Agent');
if (!ag) throw new Error('нет AI Agent');
let sm = ag.parameters.options.systemMessage;
if (sm.includes('ДАННЫЕ ИЗ ДОКУМЕНТОВ')) { console.log('уже есть — пропускаю'); fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2)); process.exit(0); }

const block =
`=== ДАННЫЕ ИЗ ДОКУМЕНТОВ И АНАЛИЗОВ (заноси в память) ===
Когда клиент присылает документ, выписку, фото анализов или таблицу с измеримыми показателями (лабораторные анализы, состав тела, обхваты, давление, пульс покоя и т.п.) — НЕ ограничивайся комментарием: ИЗВЛЕКИ значимые значения и ЗАПИШИ их в память, чтобы учитывать в дальнейшем.
— Числовые показатели → log_measurement: metric — короткое понятное название показателя (например «тестостерон общий», «ГСПГ», «талия», «вес»), value — число, unit — единица из документа. Дату бери из документа, если она указана; иначе сегодня.
— Диагнозы, состояния, принимаемые препараты из выписки → save_health (это уже разрешено границей компетенции: ты фиксируешь медконтекст, но не ставишь диагноз и не назначаешь лечение).
— После записи КРАТКО перечисли клиенту, что сохранил (например: «Записал в твой профиль: тестостерон 25, ГСПГ 40, вес 82 кг — учту в рекомендациях»).
ВАЖНО: записывай ТОЛЬКО реальные значения, явно присутствующие в документе — ничего не придумывай и не додумывай; непонятный или нечитаемый показатель пропусти. Официальный диагноз по-прежнему ставит врач — твоя задача зафиксировать данные и учитывать их, тревожное мягко направить к специалисту.
`;

const anchor = '=== БЕЗОПАСНОСТЬ РЕКОМЕНДАЦИЙ ===';
if (!sm.includes(anchor)) throw new Error('не найден якорь БЕЗОПАСНОСТЬ РЕКОМЕНДАЦИЙ');
sm = sm.replace(anchor, block + '\n' + anchor);
ag.parameters.options.systemMessage = sm;

fs.writeFileSync(p, JSON.stringify(Array.isArray(raw) ? [wf] : wf, null, 2));
console.log('OK: блок ДАННЫЕ ИЗ ДОКУМЕНТОВ добавлен; systemMessage =', sm.length);

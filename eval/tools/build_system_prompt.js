/**
 * Сборка системного промпта стенда из ЭТАЛОННОЙ ВЫГРУЗКИ боевого workflow.
 *
 * До 09.09.2026 промпт восстанавливался из скриптов-трансформов: выгрузки в репозитории не
 * было. Теперь есть — knowledge/schema/ЭТАЛОН-main-workflow.json, — и промпт берётся оттуда
 * дословно. Реконструкция больше не нужна; её результат сверяется с эталоном отчётом ниже.
 *
 * Две правки, которые стенд вносит осознанно, и обе относятся к РФ-версии, а не к Claude:
 *  1. ПОРЯДОК. В боевом промпте персона идёт первой, а блок профиля — в середине. Значит
 *     кэшируемый префикс у каждого бота свой и рвётся на каждом сообщении. В РФ-версии
 *     персона и профиль уезжают в конец (research/РФ-СТЕК-план.md), и стенд меряет модели
 *     на той раскладке, которая поедет в бой.
 *  2. НОВЫЙ БЛОК «ДАННЫЕ О ЗДОРОВЬЕ» — его в боевом боте нет, он следует из требований
 *     marketing/ДАННЫЕ-О-ЗДОРОВЬЕ.md и реализован также в базе и в коде (КОНТУР-ЗДОРОВЬЯ.md).
 *
 * n8n-выражения не вырезаются, а ИСПОЛНЯЮТСЯ тем же выражением, что исполняет n8n, с
 * подставленным bot_type — иначе условная граница компетенции и хвост владельца потерялись бы.
 *
 * Прогон: node eval/tools/build_system_prompt.js
 */
const fs = require('fs');
const path = require('path');

const EXPORT = path.join(__dirname, '..', '..', 'knowledge', 'schema', 'ЭТАЛОН-main-workflow.json');
const OUTDIR = path.join(__dirname, '..', 'prompt');
const fail = (m) => { console.error('ОШИБКА: ' + m); process.exit(1); };

if (!fs.existsSync(EXPORT)) fail('нет эталонной выгрузки: ' + EXPORT);
const raw = JSON.parse(fs.readFileSync(EXPORT, 'utf8'));
const wf = Array.isArray(raw) ? raw[0] : raw;
const agent = wf.nodes.find((n) => n.name === 'AI Agent') || fail('в выгрузке нет узла AI Agent');
const source = String(agent.parameters.options.systemMessage || '');
if (source.length < 15000) fail('системник подозрительно короткий: ' + source.length);

// ---- Блок РФ-версии: в боевом боте его НЕТ ----
const rfHealth = `=== ДАННЫЕ О ЗДОРОВЬЕ (РФ, обязательно) ===
Тебе нужен не диагноз, а ограничение. Услышал про травму, болезнь, препарат или состояние — запиши через add_exclusion то, ЧТО НЕЛЬЗЯ делать (тип нагрузки, продукт, движение), и работай дальше по нему. Саму формулировку диагноза в память не переноси.
Карта здоровья (save_health: аллергии, состояния, травмы, препараты) заполняется ТОЛЬКО при полученном согласии на данные о здоровье — оно отмечено в профиле. Согласия нет: скажи коротко и по-человечески, что для хранения таких сведений нужно отдельное согласие, предложи его дать — и продолжай помогать без записи. Отказ давать согласие ничего не отключает: подписка, планы, дневник, расчёты и напоминания работают полностью. Согласие никогда не условие оплаты.
Аллергии — исключение по важности: без согласия ты их не хранишь, поэтому спрашивай про аллергены перед каждым советом о еде и предупреждай, что не запоминаешь их.
Анализы, выписки, фото тела: прочитал, объяснил, извлёк ограничения — исходник не хранится, и на это не ссылайся в будущих ответах как на сохранённое.
В долговременную выжимку о клиенте не попадают диагнозы, препараты, результаты анализов и показатели здоровья — только привычки и поведение.`;

// ---- Исполнение n8n-выражений ровно так, как это делает n8n ----
const resolve = (text, bot_type) => text.replace(/\{\{([\s\S]*?)\}\}/g, (all, expr) => {
  if (/^(PERSONA|PROFILE)$/.test(expr.trim())) return all;
  const json = new Proxy({ bot_type }, {
    get: (t, k) => (k === 'bot_type' ? bot_type
      : k === 'system_prompt' ? '{{PERSONA}}'
      : k === 'profile_block' ? '{{PROFILE}}'
      : ''),
  });
  const $ = () => ({ first: () => ({ json }) });
  try { return String(new Function('$', 'return (' + expr + ')')($) ?? ''); }
  catch (e) { fail('не вычислилось n8n-выражение: ' + expr.slice(0, 80) + ' — ' + e.message); }
});

const MUST = [
  '103', '112', 'РПП', 'суицид', 'телефоны доверия НЕ называй',
  'check_recipe_allergens ОБЯЗАТЕЛЬНО', 'марципан→миндаль',
  'НЕ вычисляй день недели', 'ПОТРАЧЕНО СЕГОДНЯ НА АКТИВНОСТИ',
  'ТОЛЬКО инструментом calculate', '[[кнопки:', 'разметка не работает',
  'set_reminder', 'lookup_food', 'log_food', 'log_workout', 'save_health',
  '=== КОНФИДЕНЦИАЛЬНОСТЬ', '=== ГРАМОТНОСТЬ', '=== УСТОЙЧИВОСТЬ ПРАВИЛ',
  '=== ДАННЫЕ О ЗДОРОВЬЕ', 'ограничение', 'отдельное согласие',
  '{{PERSONA}}', '{{PROFILE}}',
];

let report = [];
for (const bt of ['client', 'owner', 'trusted']) {
  const resolved = resolve(source, bt);

  // Персона и профиль уезжают в конец: длинный префикс становится общим для всех ботов.
  const globals = resolved.replace('{{PERSONA}}', '').replace('{{PROFILE}}', '');
  const text = (globals.trimStart() + '\n\n' + rfHealth
    + '\n\n=== ПЕРСОНА ===\n{{PERSONA}}\n\n{{PROFILE}}\n')
    .replace(/\n{3,}/g, '\n\n');

  const missing = MUST.filter((k) => text.indexOf(k) === -1);
  if (missing.length) fail(bt + ': в промпте нет ключевых правил: ' + missing.join(' | '));
  const stray = (text.match(/\{\{(?!PERSONA|PROFILE)/g) || []).length;
  if (stray) fail(bt + ': остались невычисленные n8n-выражения: ' + stray);
  const hasBorder = text.indexOf('ГРАНИЦА КОМПЕТЕНЦИИ') !== -1;
  if ((bt === 'client') !== hasBorder) fail(bt + ': граница компетенции стоит не там, где должна');
  const ownerTail = text.indexOf('он сам ставит себе цели') !== -1;
  if ((bt === 'owner') !== ownerTail) fail(bt + ': хвост владельца в блоке фото стоит не там, где должен');
  if (text.indexOf('{{PROFILE}}') < text.indexOf('=== НАПОМИНАНИЯ')) {
    fail(bt + ': профиль не уехал в конец — кэш префикса рвётся на каждом сообщении');
  }

  fs.writeFileSync(path.join(OUTDIR, 'system_message.' + bt + '.txt'), text, 'utf8');
  report.push({ bt, len: text.length, blocks: (text.match(/^=== /gm) || []).length });
  console.log(`OK -> prompt/system_message.${bt}.txt | блоков: ${(text.match(/^=== /gm) || []).length}`
    + ` | знаков: ${text.length} | ~токенов: ${Math.round(text.length / 2.7)}`);
}
console.log('  источник: эталонная выгрузка, системник ' + source.length + ' знаков, узлов '
  + wf.nodes.length + '; персона и профиль перенесены в конец, добавлен блок ДАННЫЕ О ЗДОРОВЬЕ');
